def lsb(bb: int) -> int:
    return (bb & -bb).bit_length() - 1


def msb(bb: int) -> int:
    return bb.bit_length() - 1


def pack_move(frm: int, to: int, promo: int = 0, flags: int = 0) -> int:
    return frm | (to << 6) | (promo << 12) | flags


def m_from(move: int) -> int:
    return move & 63


def m_to(move: int) -> int:
    return (move >> 6) & 63


def m_promo(move: int) -> int:
    return (move >> 12) & 7


def move_uci(move: int) -> str:
    s = SQ_NAMES[move & 63] + SQ_NAMES[(move >> 6) & 63]
    promo = (move >> 12) & 7
    if promo:
        s += PROMO_CHARS[promo]
    return s
