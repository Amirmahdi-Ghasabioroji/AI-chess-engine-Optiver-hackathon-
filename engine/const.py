ADJ_FILES = [0] * 8
for _f in range(8):
    if _f > 0:
        ADJ_FILES[_f] |= FILE_BB[_f - 1]
    if _f < 7:
        ADJ_FILES[_f] |= FILE_BB[_f + 1]
for _sq in range(64):
    _f, _r = _sq % 8, _sq // 8
    ISOLATED[_sq] = ADJ_FILES[_f]
    _fw = _fb = 0
    for _rr in range(_r + 1, 8):
        for _ff in (_f - 1, _f, _f + 1):
            if 0 <= _ff < 8:
                _fw |= 1 << (_rr * 8 + _ff)
    for _rr in range(_r - 1, -1, -1):
        for _ff in (_f - 1, _f, _f + 1):
            if 0 <= _ff < 8:
                _fb |= 1 << (_rr * 8 + _ff)
    PASSED_W[_sq] = _fw
    PASSED_B[_sq] = _fb
